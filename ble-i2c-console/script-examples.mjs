// Based on TI SLVUCR8B sections 4.5/5.2 and SLVAFV8A.
export const REFERENCE_SCRIPT = `// Select the TPS25751 Low Region Binary generated by TI's configuration tool.
const TPS_ADDR = 0x20;    // Fundamental address set by your ADCIN pins.
const PATCH_ADDR = 0x30;  // Must be unused and different from TPS_ADDR.
const REG_CMD = 0x08;
const REG_DATA = 0x09;
if (!file.length || file.length > 32768) throw new Error("Select a Low Region Binary of 1–32768 bytes.");
if (PATCH_ADDR === TPS_ADDR) throw new Error("Patch address must differ from the fundamental address.");

async function readRegister(register, count) {
  const reply = await i2c.writeRead(TPS_ADDR, [register], count + 1);
  if (reply[0] < count) throw new Error("Short register response at 0x" + register.toString(16));
  return reply.slice(1);
}
async function writeRegister(register, bytes) {
  if (bytes.length > 64) throw new Error("TPS register payload exceeds 64 bytes.");
  await i2c.write(TPS_ADDR, [register, bytes.length, ...bytes]);
}
async function waitCommandComplete() {
  const deadline = Date.now() + 2000;
  for (let attempt = 0; attempt < 100 && Date.now() < deadline; attempt++) {
    const command = await readRegister(REG_CMD, 4);
    if (command.every(byte => byte === 0)) return;
    if (text(command) === "!CMD") throw new Error("TPS25751 rejected the 4CC command (!CMD).");
    await sleep(10);
  }
  throw new Error("CMD1 did not clear before the polling deadline.");
}
async function command(name) {
  await writeRegister(REG_CMD, ascii(name));
  await sleep(1); // TI requires at least 500 microseconds after PBMs.
  await waitCommandComplete();
}

// Upload BEFORE starting PBMs: BLE latency must not consume its 5-second timer.
log("Buffering " + fileName + " on the bridge (" + file.length + " bytes)…");
await i2c.stage(file);
const initialMode = text(await readRegister(0x03, 4));
if (initialMode !== "PTCH") throw new Error("Expected PTCH mode; got " + JSON.stringify(initialMode) + ". Reset/configure the PD controller for host patch loading.");
let ready = false;
for (let attempt = 0; attempt < 50; attempt++) {
  const events = await readRegister(0x14, 11);
  if (events[10] & 0x02) { ready = true; break; } // ReadyForPatch, bit 81.
  await sleep(20);
}
if (!ready) throw new Error("ReadyForPatch is not set. Reset the PD controller before retrying.");
await waitCommandComplete();
// Enable and clear PatchLoaded (bit 80), preserving all other interrupt masks.
const interruptMask = await readRegister(0x16, 11);
interruptMask[10] |= 0x01;
await writeRegister(0x16, interruptMask);
const clearLoaded = new Uint8Array(11);
clearLoaded[10] = 0x01;
await writeRegister(0x18, clearLoaded);

// DATA1 input: total bundle size (uint32 LE), patch target address, timeout.
const size = file.length;
await writeRegister(REG_DATA, [size & 255, (size >>> 8) & 255,
  (size >>> 16) & 255, (size >>> 24) & 255, PATCH_ADDR, 0x32]);
await command("PBMs");
const startStatus = (await readRegister(REG_DATA, 1))[0];
if (startStatus !== 0) throw new Error("PBMs failed: " + hex([startStatus]));

// Raw binary to PATCH_ADDR: NO register number or length byte is prepended.
// The complete staged file is written locally as one continuous I2C transaction.
log("Streaming staged binary to patch address 0x" + PATCH_ADDR.toString(16));
await i2c.writeStaged(PATCH_ADDR);
progress(file.length, file.length);

// PBMc is sent to the fundamental address, then CMD1 and DATA1 are checked.
await command("PBMc");
const status = await readRegister(REG_DATA, 64);
log("PBMc DATA1: " + hex(status));
if (status.slice(0, 4).some(byte => byte !== 0)) {
  throw new Error("PBMc returned nonzero patch/configuration status: " + hex(status.slice(0, 4)));
}
await sleep(20);
for (let attempt = 0; attempt < 50; attempt++) {
  const events = await readRegister(0x14, 11);
  const mode = text(await readRegister(0x03, 4));
  if ((events[10] & 0x01) && mode === "APP ") { log("Patch loaded. Post-Patch Mode: APP "); return; }
  await sleep(20);
}
throw new Error("Patch completion did not transition MODE to APP with PatchLoaded set.");
`;
export const LARGE_READ_SCRIPT = `// Example: one register command, then a continuous 64-byte I²C read.
const address = 0x20;
const data = await i2c.writeRead(address, [0x09], 64);
log("Read " + data.length + " bytes:");
log(hex(data));
`;
